"""Build docs/services/ and the site menu from services.yml.

Copies each fetched service's docs folder into docs/services/<name>/ and writes
the site menu (docs/.nav.yml) with one tab per role. A role's tab lists, for
each service, its Overview and the pages in its user/, operator/ or developer/
folder. Each tab starts with an overview table (docs/services/<tab>.md).
"""

import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / ".cache" / "repos"
DOCS = ROOT / "docs"
SERVICES_DIR = DOCS / "services"

# role (folder name in a service's docs), overview page, tab title
ROLES = [
    ("user", "users", "End users"),
    ("operator", "operators", "Node operators"),
    ("developer", "developers", "Developers"),
]


def fetch(service):
    name, repo, ref, path = service["name"], service["repo"], service["ref"], service["path"]
    clone = CACHE / name
    shutil.rmtree(clone, ignore_errors=True)
    subprocess.run(
        ["git", "clone", "--quiet", "--depth", "1", "--branch", ref,
         f"https://github.com/{repo}.git", str(clone)],
        check=True,
    )
    source = clone / path
    if not source.is_dir() or source.is_symlink():
        sys.exit(f"{repo}@{ref} has no '{path}' folder")
    # Symlinks could pull files from outside the repo into the public site.
    links = [p for p in source.rglob("*") if p.is_symlink()]
    if links:
        sys.exit(f"{repo}@{ref}: symlinks are not allowed in docs: "
                 + ", ".join(str(p.relative_to(clone)) for p in links))
    target = SERVICES_DIR / name
    shutil.rmtree(target, ignore_errors=True)
    shutil.copytree(source, target, symlinks=True)
    print(f"{name}: {repo}@{ref}/{path} -> {target.relative_to(ROOT)}")


def role_nav(service, role):
    """Menu entries of a service in a role's tab; empty if it has none."""
    if "links" in service:
        return [{link["title"]: link["url"]} for link in service["links"] if role in link["roles"]]
    root = SERVICES_DIR / service["name"]
    entries = []
    for folder in sorted(p for p in root.rglob(role) if p.is_dir()):
        pages = f"{folder.relative_to(DOCS).as_posix()}/*.md"
        part = folder.parent.relative_to(root)
        # A service with several parts has role folders inside each part.
        entries.append({part.as_posix(): [pages]} if part.parts else pages)
    if entries:
        # Each tab gets its own copy of the Overview, so opening it keeps that
        # tab selected. The copy sits next to index.md, so its links still work.
        shutil.copy(root / "index.md", root / f"overview-{role}.md")
        entries.insert(0, {"Overview": f"services/{service['name']}/overview-{role}.md"})
    return entries


def write_overview(role, page, title, services):
    rows = []
    for service in services:
        if "links" in service:
            first = next(iter(role_nav(service, role)[0].values()))
            docs = f"[{service['title']}]({first})"
        else:
            docs = f"[{service['title']}]({service['name']}/overview-{role}.md)"
        rows.append(f"| {service['title']} | {service['description']} | {docs} |")
    (SERVICES_DIR / f"{page}.md").write_text(
        "<!-- Generated by scripts/fetch_services.py from services.yml -->\n\n"
        f"# {title}\n\n"
        "| Service | Description | Documentation |\n"
        "|---|---|---|\n"
        + "\n".join(rows) + "\n\n"
        "Descriptions are based on each repository's GitHub description.\n\n"
        "To add a service, follow the [service docs template](../contributing/service-docs-template.md).\n"
    )


def write_nav(services):
    nav = [{"Home": "index.md"}]
    for role, page, title in ROLES:
        tab = [{"Overview": f"services/{page}.md"}]
        listed = []
        for service in services:
            entries = role_nav(service, role)
            if entries:
                tab.append({service["title"]: entries})
                listed.append(service)
        write_overview(role, page, title, listed)
        nav.append({title: tab})
    nav.append("contributing")
    text = yaml.safe_dump({"nav": nav}, sort_keys=False, allow_unicode=True)
    (DOCS / ".nav.yml").write_text("# Generated by scripts/fetch_services.py from services.yml\n" + text)


def main():
    services = yaml.safe_load((ROOT / "services.yml").read_text())["services"]
    SERVICES_DIR.mkdir(parents=True, exist_ok=True)
    fetched = {s["name"] for s in services if "links" not in s}
    # Remove folders of services that are no longer listed.
    for old in SERVICES_DIR.iterdir():
        if old.is_dir() and old.name not in fetched:
            shutil.rmtree(old)
    for service in services:
        if "links" not in service:
            fetch(service)
    write_nav(services)


if __name__ == "__main__":
    main()
